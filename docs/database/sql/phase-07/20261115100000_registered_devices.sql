CREATE TABLE registered_devices (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 public_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 device_uuid CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 tenant_id BIGINT UNSIGNED NOT NULL,
 shop_id BIGINT UNSIGNED NOT NULL,
 display_name VARCHAR(100) NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
 credential_hash VARBINARY(255) NOT NULL,
 registered_by_user_id INT UNSIGNED NOT NULL,
 registered_at DATETIME(6) NOT NULL,
 last_validated_at DATETIME(6) NULL,
 offline_trust_expires_at DATETIME(6) NULL,
 last_sync_started_at DATETIME(6) NULL,
 last_sync_completed_at DATETIME(6) NULL,
 last_seen_at DATETIME(6) NULL,
 revoked_at DATETIME(6) NULL,
 revoked_by_user_id INT UNSIGNED NULL,
 revocation_reason VARCHAR(500) NULL,
 created_at DATETIME(6) NOT NULL,
 updated_at DATETIME(6) NOT NULL,
 CONSTRAINT uq_registered_devices_public UNIQUE (public_id),
 CONSTRAINT uq_registered_devices_uuid UNIQUE (device_uuid),
 INDEX ix_registered_devices_scope (tenant_id,shop_id,status),
 INDEX ix_registered_devices_seen (status,last_seen_at),
 CONSTRAINT ck_registered_devices_public CHECK (public_id REGEXP '^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$'),
 CONSTRAINT ck_registered_devices_uuid CHECK (device_uuid REGEXP '^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$'),
 CONSTRAINT ck_registered_devices_name CHECK (CHAR_LENGTH(TRIM(display_name)) BETWEEN 1 AND 100),
 CONSTRAINT ck_registered_devices_status CHECK (status IN ('PENDING','ACTIVE','REVOKED')),
 CONSTRAINT ck_registered_devices_verifier CHECK (OCTET_LENGTH(credential_hash) BETWEEN 32 AND 255),
 CONSTRAINT ck_registered_devices_revocation CHECK ((status='REVOKED' AND revoked_at IS NOT NULL AND revoked_by_user_id IS NOT NULL AND revocation_reason IS NOT NULL AND CHAR_LENGTH(TRIM(revocation_reason))>0) OR (status<>'REVOKED' AND revoked_at IS NULL AND revoked_by_user_id IS NULL AND revocation_reason IS NULL)),
 CONSTRAINT fk_registered_devices_tenant FOREIGN KEY (tenant_id) REFERENCES tenants(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
 CONSTRAINT fk_registered_devices_shop FOREIGN KEY (tenant_id,shop_id) REFERENCES shops(tenant_id,id) ON UPDATE RESTRICT ON DELETE RESTRICT,
 CONSTRAINT fk_registered_devices_registrar FOREIGN KEY (registered_by_user_id) REFERENCES users(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
 CONSTRAINT fk_registered_devices_revoker FOREIGN KEY (revoked_by_user_id) REFERENCES users(id) ON UPDATE RESTRICT ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
