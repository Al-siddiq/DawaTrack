import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { gzipSync } from 'node:zlib';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const at = (...parts) => path.join(root, ...parts);
const source = JSON.parse(fs.readFileSync(at('resources/ui/icons.json'), 'utf8'));
const packageRoot = at('node_modules/bootstrap-icons');
const installed = JSON.parse(fs.readFileSync(path.join(packageRoot, 'package.json'), 'utf8'));
if (source.library !== installed.name || source.version !== installed.version) {
    throw new Error('Icon dependency does not match resources/ui/icons.json. Run npm ci.');
}

const entries = Object.entries(source.icons).sort(([a], [b]) => a.localeCompare(b, 'en'));
const bodies = {};
const symbols = entries.map(([semantic, upstream]) => {
    if (!/^[a-z][a-z0-9-]*$/.test(semantic) || !/^[a-z][a-z0-9-]*$/.test(upstream)) {
        throw new Error(`Invalid icon name: ${semantic}`);
    }
    const svg = fs.readFileSync(path.join(packageRoot, 'icons', `${upstream}.svg`), 'utf8');
    const match = svg.match(/^<svg\b[^>]*viewBox="0 0 16 16"[^>]*>([\s\S]*)<\/svg>\s*$/);
    if (!match || /<(?:script|style|foreignObject)|\bon\w+\s*=|\b(?:href|style)\s*=/i.test(match[1])) {
        throw new Error(`Unexpected upstream SVG structure: ${upstream}`);
    }
    bodies[semantic] = match[1].trim();
    return `<symbol id="ui-${semantic}" viewBox="0 0 16 16">${bodies[semantic]}</symbol>`;
});
const sprite = `<svg xmlns="http://www.w3.org/2000/svg">${symbols.join('')}</svg>\n`;
const hash = crypto.createHash('sha256').update(sprite).digest('hex');
const file = `icons-${hash.slice(0, 16)}.svg`;
const assetUrl = `/assets/ui/${file}`;
const map = Object.fromEntries(entries.map(([semantic]) => [semantic, `ui-${semantic}`]));
const generated = 'Generated by scripts/build-ui-icons.mjs. Do not edit.';

// Keep older fingerprinted sprites for long-lived tabs. Release packaging may prune them
// only after its documented retention window; rollback must restore a coherent release.
fs.mkdirSync(at('public/assets/ui'), { recursive: true });
fs.writeFileSync(at('public/assets/ui', file), sprite);
fs.copyFileSync(path.join(packageRoot, 'LICENSE'), at('public/assets/ui/bootstrap-icons-LICENSE.txt'));
const manifest = {
    generated, library: source.library, version: source.version, license: installed.license,
    sprite: assetUrl, sha256: hash, icons: Object.fromEntries(entries),
    bytes: Buffer.byteLength(sprite), gzipBytes: gzipSync(sprite, { level: 9 }).length,
    budget: { rawBytes: 32768, gzipBytes: 8192 },
};
if (manifest.bytes > manifest.budget.rawBytes || manifest.gzipBytes > manifest.budget.gzipBytes) {
    throw new Error('Selected icon sprite exceeds the documented 32 KiB / 8 KiB gzip budget.');
}
fs.writeFileSync(at('public/assets/ui/manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
fs.mkdirSync(at('resources/js/components/ui'), { recursive: true });
fs.writeFileSync(at('resources/js/components/ui/icon-catalogue.js'), `// ${generated}\nexport const iconSprite = ${JSON.stringify(assetUrl)};\nexport const iconSymbols = Object.freeze(${JSON.stringify(map, null, 4)});\n`);
fs.writeFileSync(at('app/Support/UiIconCatalogue.php'), `<?php\n\ndeclare(strict_types=1);\n\nnamespace App\\Support;\n\n/** ${generated} */\nfinal class UiIconCatalogue\n{\n    public const SPRITE = '${assetUrl}';\n\n    public const SYMBOLS = [\n${entries.map(([key]) => `        '${key}' => 'ui-${key}',`).join('\n')}\n    ];\n}\n`);
// Trusted inline vectors let the standalone design review work with its network disabled.
fs.mkdirSync(at('docs/ui/reference'), { recursive: true });
fs.writeFileSync(at('docs/ui/reference/icon-vectors.json'), `${JSON.stringify(bodies, null, 2)}\n`);
console.log(`UI icons built: ${entries.length} symbols, ${manifest.bytes} bytes (${manifest.gzipBytes} gzip).`);
