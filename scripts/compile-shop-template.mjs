import fs from 'node:fs';
import path from 'node:path';
import { compile } from '@vue/compiler-dom';

const root = process.cwd();

const phpViewPath = path.join(
    root,
    'app',
    'Views',
    'shop',
    'index.php'
);

const templatePath = path.join(
    root,
    'resources',
    'js',
    'shop',
    'template.html'
);

const renderPath = path.join(
    root,
    'resources',
    'js',
    'shop',
    'render.js'
);

let template;

if (fs.existsSync(templatePath)) {
    template = fs.readFileSync(
        templatePath,
        'utf8'
    );
} else {
    const source = fs.readFileSync(
        phpViewPath,
        'utf8'
    );

    const match = source.match(
        /<div id="shop-app" v-cloak>([\s\S]*)<\/div>\s*<\?=\s*\$this->endSection\(\)\s*\?>/
    );

    if (!match) {
        throw new Error(
            'Could not extract the Shop Vue template from app/Views/shop/index.php.'
        );
    }

    template = `<div>${match[1]}</div>`;

    /*
     * Inline style bindings conflict with DawaTrack's CSP.
     * The branding preview receives its dynamic colours through
     * a nonce-authorized style element instead.
     */
    template = template.replace(
        /\s+:style="previewStyle"/g,
        ''
    );

    fs.writeFileSync(
        templatePath,
        template,
        'utf8'
    );

    console.log(
        'Created resources/js/shop/template.html'
    );
}

const result = compile(
    template,
    {
        mode: 'function',
        prefixIdentifiers: true,
        hoistStatic: true,
        cacheHandlers: true,
    }
);

let code = result.code;

if (!code.includes('return function render')) {
    throw new Error(
        'Unexpected Vue compiler output.'
    );
}

code = code.replace(
    'return function render',
    'export function render'
);

const output = `/*
 * Generated file.
 * Source: resources/js/shop/template.html
 * Do not edit this file manually.
 */

const Vue = window.Vue;

${code}
`;

fs.writeFileSync(
    renderPath,
    output,
    'utf8'
);

console.log(
    'Generated resources/js/shop/render.js'
);